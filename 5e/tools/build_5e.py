#!/usr/bin/env python3
"""Assemble Mutagen 5e from 5e/src/*.md.

Writes (paths relative to 5e/):
  Mutagen_5e_Class.md     class, Surge parts, Mutation trees, Forms, Overload tables (src 01-05)
  Mutagen_5e_Options.md   background, feats, gear (src 06)
  Mutagen_5e_Bestiary.md  stat blocks (src 07, generated by tools/bestiary.py)
  Mutagen_5e.md           the whole book with a contents list (src 00-08)
Run: python3 5e/tools/build_5e.py [--check]   (--check: exit 1 if any output is stale or a link/image is broken)
"""
import os, re, sys, subprocess, glob

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))     # 5e/
SRC = os.path.join(HERE, 'src')

def slug(h):
    h = re.sub(r'[*_`]', '', h.strip()).lower()
    h = re.sub(r'[^\w\s-]', '', h)
    return re.sub(r'\s+', '-', h)

def fix_paths(md):  # src files live one level deeper than outputs
    return md.replace('](../../art/', '](../art/')

def read(n): return open(os.path.join(SRC, n), encoding='utf-8').read().rstrip() + '\n'

def toc(md):
    out = ['## Contents', '']
    seen = {}
    for line in md.splitlines():
        m = re.match(r'^(#{1,3}) (.+)$', line)
        if not m or m.group(2) == 'Contents': continue
        lvl, t = len(m.group(1)), m.group(2)
        s = slug(t); n = seen.get(s, 0); seen[s] = n + 1
        if n: s = '%s-%d' % (s, n)
        if lvl == 1 and t == 'Mutagen 5e': continue
        out.append('%s- [%s](#%s)' % ('  ' * (lvl - 1), re.sub(r'[*]', '', t), s))
    return '\n'.join(out) + '\n'

def outputs():
    files = sorted(os.path.basename(p) for p in glob.glob(os.path.join(SRC, '*.md')))
    cls = [f for f in files if f[:2] in ('01', '02', '03', '04', '05')]
    o = {}
    o['Mutagen_5e_Class.md'] = fix_paths('\n'.join(read(f) for f in cls))
    o['Mutagen_5e_Options.md'] = fix_paths(read('06_options.md'))
    o['Mutagen_5e_Bestiary.md'] = fix_paths(read('07_bestiary.md'))
    body = '\n'.join(read(f) for f in files if f != '00_front.md')
    front = read('00_front.md')
    book = front + '\n' + toc(front + body) + '\n' + body
    o['Mutagen_5e.md'] = '<!-- GENERATED by 5e/tools/build_5e.py from 5e/src/. Edit the sources, not this file. -->\n' + fix_paths(book)
    return o

def verify(o):
    probs = []
    for name, md in o.items():
        ids, seen = set(), {}
        for line in md.splitlines():
            m = re.match(r'^#{1,6} (.+)$', line)
            if m:
                s = slug(m.group(1)); n = seen.get(s, 0); seen[s] = n + 1
                ids.add(s if n == 0 else '%s-%d' % (s, n))
        for a in re.findall(r'\]\(#([^)]+)\)', md):
            if a not in ids: probs.append('%s: broken anchor #%s' % (name, a))
        for img in re.findall(r'!\[[^\]]*\]\(([^)]+)\)', md):
            if not os.path.exists(os.path.normpath(os.path.join(HERE, img))): probs.append('%s: missing image %s' % (name, img))
        if '{{' in md or '{%' in md: probs.append('%s: Liquid braces would break Jekyll' % name)
    return probs

def main():
    r = subprocess.run([sys.executable, os.path.join(HERE, 'tools', 'bestiary.py'), '--check'], capture_output=True, text=True)
    if r.returncode: print(r.stdout); sys.exit('bestiary CR check failed')
    o = outputs()
    probs = verify(o)
    if '--check' in sys.argv:
        stale = [n for n, md in o.items() if not os.path.exists(os.path.join(HERE, n)) or open(os.path.join(HERE, n), encoding='utf-8').read() != md]
        for p in probs + ['stale: ' + s for s in stale]: print(p)
        print('5e build check: %s' % ('OK' if not probs and not stale else 'FAIL'))
        sys.exit(1 if probs or stale else 0)
    for n, md in o.items():
        open(os.path.join(HERE, n), 'w', encoding='utf-8').write(md)
    words = len(re.findall(r'\w+', o['Mutagen_5e.md']))
    print('wrote %s (%d words)' % (', '.join(o), words))
    for p in probs: print('PROBLEM', p)
    if probs: sys.exit(1)

if __name__ == '__main__': main()

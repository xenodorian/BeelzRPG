"""Writes arcade/roster.js: the ch 10 roster (tools/encounter_roster.py, the same data the sims and the stat blocks use)
plus the measured BR/MR ratings for parties of 2-6 (tools/sim_results/04_ratings_final.json).
Run after changing the roster:  python3 tools/export_arcade_roster.py      Check only:  python3 tools/export_arcade_roster.py --check"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import encounter_roster as RO
RAT = json.load(open(os.path.join(HERE, 'sim_results', '04_ratings_final.json')))
# Creatures that are machines (Intrude and EMP grenades work on them). Everything else is flesh, however mutated.
MACHINES = {'Turret Drone', 'Damper Drone', 'Seraph Gunship', 'Hunter-Killer Unit', 'Cleaner Hound', 'Ostrander Paladin', 'Reactor Wraith', 'Riot Line Trooper'}
def clean(b):
    keep = ('name', 'T', 'role', 'kind', 'faction', 'guard', 'tn', 'hp', 'armor', 'actions', 'interrupts', 'traits', 'attacks', 'speed',
            'look', 'tactics', 'melee', 'shift', 'summoned')
    o = {k: b[k] for k in keep if k in b}
    o['traits'] = {k: (list(v) if isinstance(v, tuple) else v) for k, v in b['traits'].items()}
    o['machine'] = b['name'] in MACHINES
    o['ratings'] = RAT.get(b['name'], {})
    return o
def tojson(x):
    return json.dumps(x, sort_keys=True, separators=(',', ':'), default=lambda v: list(v) if isinstance(v, tuple) else str(v))
roster = [clean(b) for b in RO.ROSTER]
summons = {k: clean(v) for k, v in RO.SUMMONS.items()}
out = ('/* GENERATED by tools/export_arcade_roster.py from tools/encounter_roster.py + sim_results/04_ratings_final.json: DO NOT EDIT.\n'
       '   Ratings: b<P>/m<P> = BR/MR for a party of P (-2 = "<1", 13 = "10+"). */\n'
       '(function (root) {\nroot.MUTAGEN_ROSTER = ' + tojson(dict(roster=roster, summons=summons,
       table=dict(guard=RO.GUARD, tn=RO.TN, hp=RO.HP, dmg=RO.DMG, bonus=RO.BONUS))) +
       ';\n})(typeof window !== "undefined" ? window : globalThis);\n')
target = os.path.join(HERE, '..', 'arcade', 'roster.js')
if '--check' in sys.argv:
    cur = open(target).read() if os.path.exists(target) else ''
    if cur != out: print('arcade/roster.js is STALE: run python3 tools/export_arcade_roster.py'); sys.exit(1)
    print('arcade/roster.js in sync with tools/encounter_roster.py')
else:
    open(target, 'w').write(out); print('wrote', target, len(out), 'bytes,', len(roster), 'creatures')

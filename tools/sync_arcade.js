// Copies the builder's game data and rules engine into arcade/mutagen_rules.js so the Arcade uses exactly the
// builder's rules (derive, legality, randomChar, examples...). builder/index.html stays the single source of truth.
// Run after any builder change:  node tools/sync_arcade.js        Check only (CI/tests):  node tools/sync_arcade.js --check
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'builder/index.html'), 'utf8');
const data = html.match(/(\/\* =+\s*MUTAGEN GAME DATA[\s\S]*?END OF GAME DATA =+ \*\/)/);
if (!data) throw new Error('builder data block not found');
const a = html.indexOf('const D = MUTAGEN;'), b = html.indexOf('/* ---------- UI ---------- */');
if (a < 0 || b < 0 || b < a) throw new Error('builder rules section not found');
const rules = html.slice(a, b).replace(/^const DOC = .*$/m, '// (DOC links removed: not needed outside the builder UI)');
const tf = html.match(/^function twistFits\(t, sh\) \{.*\}$/m);
if (!tf) throw new Error('twistFits not found');
const out = `/* GENERATED by tools/sync_arcade.js from builder/index.html: DO NOT EDIT BY HAND.
   The builder is the source of truth for the character rules; rerun the sync after changing it. */
(function (root) {
"use strict";
${data[1]}
${rules}
${tf[0]}
root.MUTAGEN = MUTAGEN;
root.MutagenRules = { D, derive, normalize, blank, randomChar, randomSurge, fromExample, gate, picks, formStats, countRoles, roleOf,
  evoNodes, lvl, stageIdx, surgeCalc, twistFits, estimateScrip, looksLikeCharacter, growNodes,
  NODE, NODE_TREE, TREE, FORM, SHAPE, EFFECT, TWIST, ORIGIN, KIT, ITEM, SCAR, INJ, FRAME, MOD, STAT_IDS, STAT_NAME, ROLES, TIER_NAME, isEvo, esc, sgn };
})(typeof window !== "undefined" ? window : globalThis);
`;
const target = path.join(root, 'arcade/mutagen_rules.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== out) { console.log('arcade/mutagen_rules.js is STALE: run node tools/sync_arcade.js'); process.exit(1); }
  console.log('arcade/mutagen_rules.js in sync with builder/index.html');
} else { fs.writeFileSync(target, out); console.log('wrote', target, out.length, 'bytes'); }
